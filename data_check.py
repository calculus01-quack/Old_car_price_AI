import pandas as pd
df = pd.read_csv("data/raw/car_detail.csv")
print("Kích thước dataset:", df.shape)
print("Số giá trị thiếu:")
print(df.isnull().sum())
missing_percent = (df.isnull().mean() * 100).round(2)
print("Tỷ lệ thiếu (%):")
print(missing_percent)
print("Số dòng trùng lặp:")
print(df.duplicated().sum())
print("Kiểu dữ liệu:")
print(df.dtypes)
print("Thống kê dữ liệu số:")
print(df.describe())
print("Tình trạng xe:")
print(df["Tình trạng"].value_counts(dropna=False))
df_used = df[df["Tình trạng"].astype(str).str.strip()== "Xe đã dùng"].copy()
print("Số xe cũ:", len(df_used))
print("Kích thước dữ liệu xe cũ:", df_used.shape)